            resident care.
        </p>

        <h2>Who this policy is for</h2>
        <p>
            HomeLogic360 is not a consumer app. Accounts are created and issued by the care facility that
            employs you; you cannot sign yourself up. This policy explains what we do with information about
            <strong class="term">staff members who use the app</strong> and about
            <strong class="term">residents whose care is recorded in it</strong>.
        </p>

        <h2>Our role</h2>
        <div class="callout">
            <p>
                The care facility decides what resident information is collected and why. We hold and process
                that information on the facility's behalf and under its instructions. If you are a resident or
                a resident's family member and want to see, correct or delete resident records, contact the
                care facility directly - they control those records, not us.
            </p>
        </div>

        <h2>Information about staff users</h2>
        <ul>
            <li>Name, work email address, job role, and the facility and branch you are assigned to</li>
            <li>An encrypted form of your password, and session tokens stored on your device</li>
            <li>Clock-in and clock-out times, and the precise location of your device at those moments</li>
            <li>Leave requests, employee documents and shift assignments your facility records</li>
            <li>A log of actions taken in the app, so care entries can be attributed to the person who made them</li>
            <li>Notification preferences, and a push-notification address if you enable notifications</li>
        </ul>

        <h2>Location</h2>
        <p>
            When you clock in or out, the app asks your device for its current coordinates and sends them with
            the clock-in record. Your facility uses this to confirm attendance on site. Location is read only at
            the moment you tap clock in or clock out. The app does not track your location in the background,
            and it does not read your location at any other time. You can refuse the permission; clocking in
            through the app will not work without it, and you should use your facility's alternative method.
        </p>

        <h2>Information about residents</h2>
        <p>
            Staff record care information about residents, which may include medications and administration
            records, vital signs, sleep and behaviour records, assessments, incidents, appointments, care notes,
            visitor records and uploaded documents. This is health information and we treat it as sensitive.
        </p>

        <h2>How we use information</h2>
        <ul>
            <li>To operate the service - showing residents, medications, schedules and tasks to authorised staff</li>
            <li>To restrict access, so staff see only their own facility and, where applicable, their own branch</li>
            <li>To send operational notifications, such as medication windows and assigned tasks</li>
            <li>To keep an audit trail of who recorded or changed a care entry</li>
            <li>To keep the service secure and diagnose faults</li>
        </ul>
        <p>
            We do not sell personal information. We do not use it for advertising. We do not profile users or
            residents for any commercial purpose.
        </p>

        <h2>Tracking</h2>
        <p>
            The HomeLogic360 mobile app contains no third-party analytics, advertising or tracking software. It
            does not track you across other companies' apps or websites.
        </p>

        <h2>Who we share information with</h2>
        <p>We share information only with service providers that help us run HomeLogic360:</p>
        <ul>
            <li>Our hosting provider, which runs the servers and database</li>
            <li>Our email provider, used to send operational and notification email</li>
            <li>Our DNS and certificate providers, which route and secure traffic to the service</li>
        </ul>
        <p>
            These providers act on our instructions and may not use the information for their own purposes.
            We may also disclose information where the law requires it.
        </p>

        <h2>How long we keep it</h2>
        <p>
            Resident care records are retained for as long as the facility requires and for any period required
            by law that applies to care records. Staff account records are retained while the account is active
            and for a period afterwards so that care entries remain correctly attributed. We do not keep
            information for longer than these purposes require.
        </p>

        <h2>Deleting your account</h2>
        <p>
            You can request deletion of your staff account from inside the app, under Settings. Your facility's
            administrator is notified and will action the request.
        </p>
        <p>
            Care records you entered about residents are not deleted with your account. Those records belong to
            the facility, form part of a resident's care history, and in most cases must be retained by law.
            Where records are retained, your name stays attached to the entries you made, so the care history
            remains accurate and auditable.
        </p>

        <h2>Security</h2>
        <ul>
            <li>All traffic between the app and our servers is encrypted in transit using TLS</li>
            <li>Session tokens are held in your device's secure storage, not in ordinary app storage</li>
            <li>Access is role-based, and every request is scoped to your facility</li>
            <li>Passwords are stored as salted hashes and are never readable by us</li>
        </ul>

        <h2>Children</h2>
        <p>
            HomeLogic360 is a workplace tool for care staff. It is not directed at children and we do not
            knowingly create accounts for them.
        </p>

        <h2>Your rights</h2>
        <p>
            You may ask for a copy of the information we hold about you as a staff user, ask us to correct it,
            or ask us to delete it, subject to the retention rules above. Requests about resident records should
            go to the care facility, which controls them.
